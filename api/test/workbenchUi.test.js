import test from 'node:test'
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
const source = path => readFile(new URL('../../app/'+path,import.meta.url),'utf8')
test('workbench sidebar has an independent settings state and a keyboard skip link',async()=>{
 const [shell,nav]=await Promise.all([source('src/shared/components/AppShell.vue'),source('src/shared/components/PrimaryNavigation.vue')])
 assert.match(shell,/href="#workspace-content"/)
 assert.match(shell,/id="workspace-content"[^>]*tabindex="-1"/)
 assert.match(shell,/nav-sidebar-collapsed/)
 assert.match(nav,/route.path === '\/settings' \? 'page'/)
 assert.match(nav,/!item.adminOnly \|\| isAdmin.value/)
 assert.doesNotMatch(nav,/2 人在线|同步正常|在线用户/)
})
test('notes defer heavy editor and preserve its lifecycle and return focus after first use',async()=>{
 const [page,editor,preview,history]=await Promise.all([source('src/modules/whisper/Whisper.vue'),source('src/modules/whisper/components/NoteEditor.vue'),source('src/modules/whisper/components/NotePreview.vue'),source('src/modules/whisper/components/NoteVersionHistory.vue')])
 assert.match(page,/await import\('\.\/components\/NoteEditor.vue'\)/)
 assert.match(page,/<AsyncPanelState v-if="showEditor && !editorLoaded"/)
 assert.match(page,/if \(editorLoaded.value \|\| editorLoading.value\) return/)
 assert.match(page,/<NoteEditor v-if="editorLoaded"/)
 assert.match(page,/:return-focus="editorReturnFocus"/)
 assert.match(editor,/props.returnFocus\?\.isConnected/)
 assert.match(editor,/\}, \{ immediate: true \}\)/)
 assert.match(editor,/registerReloadGuard/)
 assert.match(editor,/onBeforeRouteLeave/)
 assert.match(preview,/defineAsyncComponent\(\(\) => import\('\.\/BlockContent.vue'\)\)/)
 assert.match(history,/defineAsyncComponent\(\(\) => import\('\.\/BlockContent.vue'\)\)/)
 assert.match(preview,/:aria-modal="inline \? undefined : true"/)
})
test('disclosure, reduced-motion and semantic primary action tokens remain explicit',async()=>{
 const [reset,tokens,editor,files]=await Promise.all([source('src/styles/reset.css'),source('src/styles/variables.css'),source('src/modules/whisper/components/NoteEditor.vue'),source('src/modules/files/FilesView.vue')])
 assert.match(reset,/\.reduce-motion \*/)
 assert.match(reset,/prefers-reduced-motion: reduce/)
 assert.match(tokens,/--accent-contrast:/)
 assert.doesNotMatch(tokens,/--transition-(?:fast|normal|slow):[^;]*ease/)
 assert.match(editor,/<details class="editor__properties" :open="metadataOpen"/)
 assert.match(editor,/aria-expanded="metadataOpen"/)
 assert.match(files,/<details\b[^>]*class="drive-tools"/)
 assert.match(files,/item.mutable === false/)
 assert.match(files,/registerReloadGuard/)
})
